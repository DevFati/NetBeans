    private void jButtonNuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonNuevoActionPerformed
        String mensaje="";
        boolean correcto=true;
        //Comprobamos si los diferentes campos estan bien introducidos o no. 
        if(!esNumero(jTextFieldNit.getText())){
            mensaje=mensaje+"El NIT debe de contener solo numeros \n";
            correcto=false;
        }
        
         if(!esPalabra(jTextFieldNom.getText())){
            mensaje=mensaje+"El nombre de empresa debe de contener solo palabras \n";
            correcto=false;
        }
         
          if(!esNumero(jTextFieldTelefono.getText())){
            mensaje=mensaje+"El telefono debe de contener solo numeros \n";
            correcto=false;
        }
          
           if(!esPalabra(jTextFieldConsulta.getText())){
            mensaje=mensaje+"La consulta debe de contener solo palabras \n";
            correcto=false;
        }
           
           if(!jTextFieldEmail.getText().matches("[a-zA-Z0-9_]+([.][a-zA-Z0-9_]+)*@[a-zA-Z0-9_]+([.][a-zA-Z0-9_]+)*[.][a-zA-Z]{2,5}")){
                mensaje=mensaje+"Formato de mail incorrecto \n";
            correcto=false;
           }
           
           //Si los campos estan bien introducidos indica al usuario que la operacion 
           // se realizo con exito, sino. Le lanza un mensaje de error 
           if(correcto){
               //Recogemos los datos y creamos un nuevo proveedor 
               Prov p=new Prov(jTextFieldNit.getText(),jTextFieldNom.getText(),jTextFieldTelefono.getText(),this.jComboBox1.getSelectedItem().toString(),jTextFieldConsulta.getText(),jTextFieldEmail.getText());
            //Añadimos el proveedor a la lista de proveedores 
               Lista.añadirProveedor(p);
              
                JOptionPane.showMessageDialog(this, "Proveedor añadido a la tabla", "Info", JOptionPane.INFORMATION_MESSAGE);
                
                //Vaciamos los campos 
                jTextFieldNit.setText("");
                jTextFieldNom.setText("");
                jTextFieldTelefono.setText("");
                jComboBox1.setSelectedIndex(0);
                jTextFieldConsulta.setText("");
                jTextFieldEmail.setText("");                         
           }else{
                JOptionPane.showMessageDialog(this, "Error en la introducíon de datos: \n"+mensaje, "Info", JOptionPane.ERROR_MESSAGE);

           }
           
         
    }//GEN-LAST:event_jButtonNuevoActionPerformed

