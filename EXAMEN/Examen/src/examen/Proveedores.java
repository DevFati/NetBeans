    private void loadComboBoxWithImages() {
    DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();
    //Añadimos uno a uno los dierentes elementos 
    model.addElement("España");
    model.addElement("Bélgica");
    model.addElement("Brasil");
    model.addElement("USA");
    jComboBox1.setModel(model);
    jComboBox1.setRenderer(new ListCellRenderer<String>() {
        @Override
        public Component getListCellRendererComponent(JList<? extends String> list, String value, int index, boolean isSelected, boolean cellHasFocus) {
            JLabel label = new JLabel();
            switch (value) {
                //Creamos diferentes casos para que cuando se cargue el elemto, se le 
                //asigne su icono correspondiente. 
                case "España":
                    label.setIcon(new ImageIcon(getClass().getResource("/imgs/spain25.png")));
                    label.setText("España");
                    break;
                case "Bélgica":
                    label.setIcon(new ImageIcon(getClass().getResource("/imgs/belgium25.png")));
                    label.setText("Bélgica");
                    break;
                case "Brasil":
                    label.setIcon(new ImageIcon(getClass().getResource("/imgs/brazil25.png")));
                    label.setText("Brasil");
                    break;
                case "USA":
                    label.setIcon(new ImageIcon(getClass().getResource("/imgs/usa25.png")));
                    label.setText("USA");
                    break;
            }
            if (isSelected) {
                label.setBackground(list.getSelectionBackground());
                label.setOpaque(true);
            }
            return label;
        }
    });
}

